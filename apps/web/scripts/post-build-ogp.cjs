function q(str) {
  return str.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
}

function buildOGPBlock(slug, ogp) {
  const canonicalUrl = `${BASE_URL}/blog/${slug}`;
  const fullTitle = `${ogp.title} | 古川耕太郎 公式サイト`;
  return `
  <!-- OGP for /blog/${slug} (generated by post-build-ogp.cjs) -->
  <title>${q(fullTitle)}</title>
  <meta name="description" content="${q(ogp.description)}">
  <meta property="og:title" content="${q(fullTitle)}">
  <meta property="og:description" content="${q(ogp.description)}">
  <meta property="og:image" content="${q(ogp.image)}">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:url" content="${q(canonicalUrl)}">
  <meta property="og:type" content="article">
  <meta property="og:site_name" content="Furukawa Archive OS">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:site" content="@HATAKE55555">
  <meta name="twitter:creator" content="@HATAKE55555">
  <meta name="twitter:title" content="${q(fullTitle)}">
  <meta name="twitter:description" content="${q(ogp.description)}">
  <meta name="twitter:image" content="${q(ogp.image)}">
  <link rel="canonical" href="${q(canonicalUrl)}">`;
}

function injectOGP(baseHtml, slug, ogp) {
  const ogpBlock = buildOGPBlock(slug, ogp);
  // <head> 直後に OGP ブロックを挿入（既存タグより先に来る → 優先される）
  // また既存の og: タグ / title / description があれば上書きのため削除
  let html = baseHtml;

  // 既存の og:*, twitter:*, title, description タグを除去
  html = html
    .replace(/<title>[^<]*<\/title>/gi, '')
    .replace(/<meta\s[^>]*(?:og:|twitter:|name="description")[^>]*>/gi, '')
    .replace(/<link\s[^>]*rel="canonical"[^>]*>/gi, '');

  // <head> 直後に挿入
  html = html.replace(/(<head[^>]*>)/i, `$1${ogpBlock}`);

  return html;
}

function main() {
  const indexHtmlPath = path.join(DIST_DIR, 'index.html');
  if (!fs.existsSync(indexHtmlPath)) {
    console.error('[ogp-gen] ERROR: dist/index.html not found. Run vite build first.');
    process.exit(1);
  }

  // UTF-8 で読み込む
  const baseHtml = fs.readFileSync(indexHtmlPath, 'utf8');

  let generated = 0;
  for (const [slug, ogp] of Object.entries(BLOG_OGP)) {
    const outDir = path.join(DIST_DIR, 'blog', slug);
    const outFile = path.join(outDir, 'index.html');

    fs.mkdirSync(outDir, { recursive: true });
    const html = injectOGP(baseHtml, slug, ogp);
    // UTF-8 で書き出す（BOMなし）
    fs.writeFileSync(outFile, html, { encoding: 'utf8' });

    console.log(`[ogp-gen] ✓ /blog/${slug}/`);
    generated++;
  }

  console.log(`[ogp-gen] Done. Generated ${generated} OGP pages.`);
}

main();
